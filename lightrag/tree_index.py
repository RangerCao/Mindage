"""
Tree Index storage and processing for PageIndex integration.

Stores hierarchical tree structures (mind maps) generated by PageIndex
alongside the existing knowledge graph in each workspace.

PageIndex is invoked via **MCP** (Model Context Protocol): a subprocess
running ``D:\\PageIndex-main\\mcp_server.py`` exposes the ``build_tree``
tool over stdio.  This cleanly decouples the two projects without
sys.path hacks.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path
from typing import Any

from lightrag.utils import logger


class TreeIndexStorage:
    """File-based storage for page-index tree structures.

    Trees are stored per-document under ``{working_dir}/tree_index/``.

    Layout::

        {working_dir}/
            tree_index/
                tree_meta.json           # doc_id → { doc_id, title, file, timestamp }
                doc_{hash1}.json         # one tree per document
                doc_{hash2}.json
    """

    def __init__(self, working_dir: str, workspace: str = "") -> None:
        base = Path(working_dir)
        if workspace:
            base = base / workspace
        self._dir = base / "tree_index"
        self._dir.mkdir(parents=True, exist_ok=True)
        self._meta_path = self._dir / "tree_meta.json"
        self._meta: dict[str, dict[str, Any]] = {}
        self._load_meta()

    # ------------------------------------------------------------------
    # Meta helpers
    # ------------------------------------------------------------------

    def _load_meta(self) -> None:
        if self._meta_path.is_file():
            try:
                with open(self._meta_path, "r", encoding="utf-8") as f:
                    self._meta = json.load(f)
            except Exception as e:
                logger.warning("Failed to load tree meta: %s", e)
                self._meta = {}

    def _save_meta(self) -> None:
        try:
            with open(self._meta_path, "w", encoding="utf-8") as f:
                json.dump(self._meta, f, ensure_ascii=False, indent=2)
        except Exception as e:
            logger.error("Failed to save tree meta: %s", e)

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def save_tree(
        self,
        doc_id: str,
        tree: dict[str, Any],
        *,
        title: str = "",
    ) -> str:
        """Save a tree structure for *doc_id*.

        Returns the filename of the saved tree.
        """
        filename = f"doc_{doc_id}.json"
        path = self._dir / filename
        with open(path, "w", encoding="utf-8") as f:
            json.dump(tree, f, ensure_ascii=False, indent=2)

        self._meta[doc_id] = {
            "doc_id": doc_id,
            "title": title or tree.get("doc_name", ""),
            "file": filename,
            "node_count": _count_nodes(tree.get("structure", [])),
        }
        self._save_meta()
        logger.info("Saved tree index for doc %s (%d nodes)", doc_id, self._meta[doc_id]["node_count"])
        return filename

    def get_tree(self, doc_id: str) -> dict[str, Any] | None:
        """Load the tree for *doc_id*, or None."""
        meta = self._meta.get(doc_id)
        if not meta:
            return None
        path = self._dir / meta["file"]
        if not path.is_file():
            return None
        try:
            with open(path, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception as e:
            logger.error("Failed to load tree for %s: %s", doc_id, e)
            return None

    def delete_tree(self, doc_id: str) -> None:
        """Delete the tree for *doc_id*."""
        meta = self._meta.pop(doc_id, None)
        if meta:
            path = self._dir / meta["file"]
            if path.is_file():
                path.unlink()
            self._save_meta()
            logger.info("Deleted tree index for doc %s", doc_id)

    def list_trees(self) -> list[dict[str, Any]]:
        """List all stored trees with metadata."""
        return list(self._meta.values())

    def doc_count(self) -> int:
        return len(self._meta)


def _count_nodes(structure: list[dict]) -> int:
    """Recursively count nodes in a tree structure."""
    count = 0
    for node in structure:
        count += 1
        if "nodes" in node:
            count += _count_nodes(node["nodes"])
    return count


