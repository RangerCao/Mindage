def _find_node_by_id(
    structure: list[dict], node_id: str
) -> dict | None:
    """Recursively search the tree structure for a node with the given *node_id*."""
    for node in structure:
        if node.get("node_id") == node_id:
            return node
        if "nodes" in node:
            found = _find_node_by_id(node["nodes"], node_id)
            if found is not None:
                return found
    return None


def _find_parent_by_id(
    structure: list[dict], node_id: str
) -> dict | None:
    """Find the parent dict whose ``nodes`` list contains the target *node_id*."""
    for node in structure:
        children = node.get("nodes", [])
        for child in children:
            if child.get("node_id") == node_id:
                return node
            if "nodes" in child:
                found = _find_parent_by_id(child["nodes"], node_id)
                if found is not None:
                    return found
    return None


async def expand_tree_node(
    tree: dict,
    node_id: str,
    llm_func: object,
    *,
    num_children: int = 4,
    add_text: bool = True,
) -> dict | None:
    """Use LLM to generate child nodes for the given *node_id* in *tree*.

    The LLM receives the parent node's title and summary and returns a list
    of subtopics.  New child nodes are **appended** to any existing children.

    Returns the updated tree dict, or ``None`` if the node was not found.
    """
    structure = tree.get("structure", [])
    parent = _find_node_by_id(structure, node_id)
    if parent is None:
        logger.warning("expand_tree_node: node %s not found in tree", node_id)
        return None

    parent_title = parent.get("title", "")
    parent_summary = parent.get("summary", "") or parent.get("prefix_summary", "")
    parent_text = parent.get("text", "")

    # ── Build LLM prompt ──────────────────────────────────────────────
    SYSTEM_PROMPT = (
        "你是一个知识结构化专家。请根据给定的主题，生成合理的子主题列表，"
        "用于构建思维导图。每个子主题应该与父主题紧密相关，覆盖其重要方面。"
    )

    context = f"父节点标题：{parent_title}\n"
    if parent_summary:
        context += f"父节点摘要：{parent_summary[:300]}\n"
    if parent_text:
        context += f"父节点内容：{parent_text[:500]}\n"

    USER_PROMPT = f"""请根据以下父节点主题，生成 {num_children} 个合理的子节点。

{context}
输出要求：
1. 每行输出一个子节点，格式为："子节点标题 | 简短描述"
2. 标题尽量简短（不超过 20 字），描述不超过 50 字
3. 子节点应覆盖父主题的不同方面或子组成部分
4. 只输出子节点列表，不要输出解释、说明或总结
5. 不要输出 markdown 符号或多余空行

示例：
数据结构 | 数据的逻辑组织形式
算法分析 | 评估算法效率的方法
"""

    try:
        # llm_func is an async callable that accepts (prompt, system_prompt=...)
        response = await llm_func(USER_PROMPT, system_prompt=SYSTEM_PROMPT)
        if not response or not isinstance(response, str):
            logger.warning("expand_tree_node: LLM returned empty response")
            return tree

        # ── Parse LLM response into child nodes ───────────────────────
        lines = [ln.strip() for ln in response.strip().split("\n") if ln.strip()]
        import re

        new_nodes: list[dict] = []
        node_counter = [0]

        # Count existing nodes in the whole tree to continue numbering
        def count_all(structure: list[dict]) -> int:
            total = 0
            for n in structure:
                total += 1
                if "nodes" in n:
                    total += count_all(n["nodes"])
            return total

        start_count = count_all(structure)

        # Also count existing children so numbering is correct
        existing_count = len(parent.get("nodes", []))

        for line in lines:
            # Remove leading numbering like "1." or "1、" or "- " or "* "
            line = re.sub(r"^[\d]+[.．、\)\s]\s*", "", line).strip()
            line = re.sub(r"^[-*•]\s*", "", line).strip()

            # Split by "|" or "：" or ": " or "--"
            parts = re.split(r"\s*[|：:]\s*", line, maxsplit=1)
            title = parts[0].strip()
            desc = parts[1].strip() if len(parts) > 1 else ""

            if not title:
                continue

            # Generate node_id
            next_id = start_count + len(new_nodes) + 1
            node = {
                "title": title,
                "node_id": f"{next_id:04d}",
                "summary": desc[:500] if desc else "",
                "text": desc if add_text else "",
                "nodes": [],
            }
            new_nodes.append(node)

        if not new_nodes:
            logger.warning("expand_tree_node: no valid child nodes parsed from LLM response")
            return tree

        # ── Append new nodes to parent's children ──────────────────────
        if "nodes" not in parent:
            parent["nodes"] = []
        parent["nodes"].extend(new_nodes)

        logger.info(
            "expand_tree_node: added %d children to node %s (%s)",
            len(new_nodes),
            node_id,
            parent_title,
        )
        return tree

    except Exception as exc:
        logger.error("expand_tree_node failed: %s", exc)
        return tree
