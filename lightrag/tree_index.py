def _resolve_mcp_server_path() -> str:
    """Locate ``mcp_server.py`` on disk."""
    here = Path(__file__).resolve().parent
    candidates = [
        here.parent.parent / "PageIndex-main" / "mcp_server.py",
        here.parent.parent.parent / "PageIndex-main" / "mcp_server.py",
        Path("D:/PageIndex-main/mcp_server.py"),
    ]
    for p in candidates:
        if p.is_file():
            return str(p)
    return "mcp_server.py"


def _resolve_file_path(file_path: str) -> str:
    """Resolve a possibly-relative file path by searching common locations."""
    if os.path.isfile(file_path):
        return file_path
    cwd = os.getcwd()
    for candidate in [
        os.path.join(cwd, file_path),
        os.path.join(cwd, "inputs", file_path),
        os.path.join(cwd, "inputs", "__parsed__", file_path),
        os.path.join(cwd, "rag_storage", file_path),
    ]:
        if os.path.isfile(candidate):
            logger.info("PageIndex: resolved %s -> %s", file_path, candidate)
            return candidate
    return file_path


# ---- Subprocess bridge to PageIndex --------------------------------------
#
# Instead of importing pageindex directly (which required sys.path hacks) or
# using the MCP SDK client (which has async/lifecycle issues in the LightRAG
# pipeline), we spawn a one-shot subprocess that runs
# ``D:\PageIndex-main\call_tree.py`` and captures its JSON output.
#
# The ``mcp_server.py`` is still available at D:\PageIndex-main\mcp_server.py
# as a standalone MCP server for external tools (Claude Desktop, Copilot, etc).
# ---------------------------------------------------------------------------


import subprocess


def _resolve_call_tree_script() -> str:
    """Locate ``call_tree.py`` on disk."""
    here = Path(__file__).resolve().parent
    candidates = [
        here.parent.parent / "PageIndex-main" / "call_tree.py",
        here.parent.parent.parent / "PageIndex-main" / "call_tree.py",
        Path("D:/PageIndex-main/call_tree.py"),
    ]
    for p in candidates:
        if p.is_file():
            return str(p)
    return str(Path("D:/PageIndex-main/call_tree.py"))


def _call_pageindex(file_path: str, model: str | None = None) -> dict | None:
    """Run ``call_tree.py`` as a subprocess and return the parsed tree dict."""
    script = _resolve_call_tree_script()
    args = [sys.executable, script, file_path, "temp"]
    if model:
        args.append(model)

    try:
        result = subprocess.run(
            args,
            capture_output=True,
            text=True,
            timeout=600,  # 10 min max for LLM calls
        )
    except subprocess.TimeoutExpired:
        logger.error("PageIndex subprocess timed out for %s", file_path)
        return None
    except Exception as exc:
        logger.error("PageIndex subprocess failed: %s", exc)
        return None

    if result.returncode != 0:
        logger.error(
            "PageIndex subprocess exited %d: %s",
            result.returncode,
            result.stderr[:500],
        )
        return None

    # stderr may contain progress messages; stdout has the JSON result
    # The last line of stdout is the JSON payload
    lines = result.stdout.strip().split("\n")
    # Find the last line that starts with {
    json_line = ""
    for line in reversed(lines):
        line = line.strip()
        if line.startswith("{"):
            json_line = line
            break

    if not json_line:
        logger.error("PageIndex subprocess: no JSON found in output")
        return None

    try:
        tree = json.loads(json_line)
    except json.JSONDecodeError as exc:
        logger.error("PageIndex subprocess: invalid JSON: %s", exc)
        return None

    if tree.get("error"):
        logger.error("PageIndex subprocess error: %s", tree["error"])
        return None

    return tree


